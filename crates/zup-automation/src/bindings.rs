/// The generated TypeScript source, with a header saying where it came from.
pub fn typescript() -> String {
    let config = Config::default();
    let mut out = String::new();
    out.push_str(HEADER);
    for (name, declare) in TYPES {
        let declaration = declare(&config);
        let header = format!("type {name}");
        assert!(
            declaration.starts_with(&header),
            "`{name}` did not declare itself as `{header}`"
        );
        out.push('\n');
        out.push_str("export ");
        out.push_str(declaration.trim_end());
        out.push('\n');
    }
    out
}

/// The header every reader of the file needs before the first line of it.
///
/// A generated file with no provenance is a file somebody will hand-edit, and the next
/// `cargo xtask automation generate` will silently delete the edit.
const HEADER: &str = "\
// Generated by `cargo xtask automation generate`. Do not edit.
//
// The zup automation protocol, as TypeScript. Every type below is derived from the
// Rust DTOs in `crates/zup-automation`; the JSON Schema beside this file in
// `schema/automation-v1.schema.json` is derived from the same types, and is the
// contract for a consumer that is not written in TypeScript.
//
// A consumer accepts any document whose `protocol` shares its major version, and
// ignores fields, event types, operation names, artifact kinds and diagnostic codes it
// does not know. A different major is refused. Nothing here is closed: a field may
// appear that is not declared.
//
// The decoder that reads a document into these types is `src/protocol.ts`, and it is
// hand-written on purpose - it is where the ignore-what-you-do-not-know rule lives.

";
