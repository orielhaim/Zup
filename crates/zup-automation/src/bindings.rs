/// Every type the Action is allowed to name, in dependency order.
///
/// A literal list rather than a walk of `TS::dependencies`, because the list is the
/// thing a reviewer reads: adding a field to a type is invisible, adding a *type* to the
/// protocol is a line here, and that is the change worth noticing.
/// One type's declaration: the name it is published under, and `ts-rs`'s own
/// renderer for it.
type Declaration = (&'static str, fn(&Config) -> String);

