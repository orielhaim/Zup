//! The TypeScript declarations, generated from the same types the JSON Schema is.
//!
//! One file, one command, one source of truth. The Action imports these types; it does
//! not hand-write a second copy of the envelope, because a hand-written copy is how the
//! Action and the CLI came to disagree about the shape of a result in the first place.
//!
//! Deterministic by construction: the declaration list is a literal array, `decl()`
//! depends only on the type, and the file is written with the same line endings on
//! every platform. That is what lets `cargo xtask automation check` be a diff.

